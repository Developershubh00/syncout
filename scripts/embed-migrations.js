// Copies ./drizzle migrations into src/db/migrations.generated.ts so the app
// itself (Admin → Set up database) can apply them — serverless functions
// can't read the drizzle folder at runtime. Run after `drizzle-kit generate`
// (npm run db:generate does both).
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "drizzle");
const journal = JSON.parse(fs.readFileSync(path.join(dir, "meta", "_journal.json"), "utf8"));
const list = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({ idx: e.idx, tag: e.tag, sql: fs.readFileSync(path.join(dir, `${e.tag}.sql`), "utf8") }));
fs.writeFileSync(
  path.join(__dirname, "..", "src", "db", "migrations.generated.ts"),
  "// Generated by scripts/embed-migrations.js from ./drizzle — do not edit by hand.\n" +
    "export const MIGRATIONS: { idx: number; tag: string; sql: string }[] = " +
    JSON.stringify(list, null, 2) +
    ";\n"
);
console.log(`embedded ${list.length} migration(s)`);
